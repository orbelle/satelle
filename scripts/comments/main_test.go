func TestStripGoKeepsDirectivesAndLiterals(t *testing.T) {
	src := "//go:build linux\n\n// Package p is doc.\npackage p\n\nimport _ \"embed\"\n\n// tmpl is doc.\n//\n//go:embed x.txt\nvar tmpl string\n\nconst s = \"// not a comment\" // trailing\n\nfunc f() int {\n\t// leading\n\tx := 1 /* inline */ + 2\n\n\t// gap\n\n\treturn x\n}\n\nfunc ExampleF() {\n\t// say\n\tf()\n\t// Output:\n\t// 3\n}\n"
	want := "//go:build linux\n\npackage p\n\nimport _ \"embed\"\n\n//go:embed x.txt\nvar tmpl string\n\nconst s = \"// not a comment\"\n\nfunc f() int {\n\tx := 1 + 2\n\n\treturn x\n}\n\nfunc ExampleF() {\n\tf()\n\t// Output:\n\t// 3\n}\n"
	out, found, err := stripGo([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if string(out) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", out, want)
	}
	if len(found) != 8 {
		t.Fatalf("found %d comments, want 8: %v", len(found), found)
	}
	again, found, err := stripGo(out)
	if err != nil || len(found) != 0 || string(again) != want {
		t.Fatalf("second strip changed the file: %v %v", found, err)
	}
}

func TestStripGoKeepsCgoPreamble(t *testing.T) {
	src := "package p\n\n// #include <stdio.h>\nimport \"C\"\n\n// doc\nfunc F() {}\n"
	out, found, err := stripGo([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	if len(found) != 1 || !strings.Contains(string(out), "// #include <stdio.h>\nimport \"C\"") {
		t.Fatalf("got %d found:\n%s", len(found), out)
	}
}

