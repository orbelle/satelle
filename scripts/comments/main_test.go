func TestShellComments(t *testing.T) {
	src := `#!/bin/sh
# shellcheck disable=SC2086
# doc line

set -eu
n=${#x} # count
y=${x#pre}
echo "# not" '# not' $# a#b
cat <<EOF
# heredoc body
EOF
cat <<-'X'
	# tabbed body
	X
z=$(echo hi # inner
)
w=$((1 + 2))
case $a in
a) echo a ;; # arm
esac
`
	want := `#!/bin/sh
# shellcheck disable=SC2086

set -eu
n=${#x}
y=${x#pre}
echo "# not" '# not' $# a#b
cat <<EOF
# heredoc body
EOF
cat <<-'X'
	# tabbed body
	X
z=$(echo hi
)
w=$((1 + 2))
case $a in
a) echo a ;;
esac
`
	out, found, err := stripLines([]byte(src), shellComments)
	if err != nil {
		t.Fatal(err)
	}
	if string(out) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", out, want)
	}
	if len(found) != 4 {
		t.Fatalf("found %d, want 4: %v", len(found), found)
	}
}

