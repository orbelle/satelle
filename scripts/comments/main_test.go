func TestCheckAndStripFiles(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "a.go")
	if err := os.WriteFile(p, []byte("package a\n\n// doc\nfunc A() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if code := run([]string{"check", p}); code != 1 {
		t.Fatalf("check on a commented file exited %d, want 1", code)
	}
	if code := run([]string{"strip", p}); code != 0 {
		t.Fatalf("strip exited %d", code)
	}
	if code := run([]string{"check", p}); code != 0 {
		t.Fatalf("check after strip exited %d, want 0", code)
	}
	if code := run([]string{"bogus"}); code != 2 {
		t.Fatalf("bad mode exited %d, want 2", code)
	}
}
